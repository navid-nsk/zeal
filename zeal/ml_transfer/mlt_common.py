TRAIN_END = 24 * 7 * 20
VAL_END = 24 * 7 * 24
EVAL_START = H_TOT - T     # first evaluation output hour (output at hour t uses z[t-W+1 .. t])
EPS_GRID = [0.01, 0.02, 0.05, 0.10]
