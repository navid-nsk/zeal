"""mlt_common.py -- shared objects of the ZEAL ML-transfer experiment (exp3_ml).

Declared setup (fixed BEFORE any result was looked at; see findings.md section 1):
  data    : SYNTHETIC hourly electricity-feeder loads, 12 feeders x 30 weeks (5040 h), generated by `make_data(seed=0)`
            (regional temperature: stationary mean + daily cycle + 2-3-day weather fronts (hourly AR(1) phi 0.98, sd 3.5 C); per-feeder residential/
            commercial daily-weekly profile, cooling sensitivity, linear growth, one step change for some feeders,
            AR(1) noise).  Declared synthetic: no public dataset was downloaded.
  task    : peak-risk classifier.  Label at hour t = 1{ max load over (t, t+h] > cap_j }, cap_j = 80th percentile of the
            feeder's training-period maxima over blocks of h hours; h = 24 (models 'mlp', 'feat': next-day risk) or h = 168
            (models 'mlp7', 'feat7': next-week capacity risk).  Input = the past W = 168 hours of the feeder's z-scored load
            (z = (load - mean_j)/sd_j with training-period statistics).  Output f(t) = P(peak in next 24 h).
  models  : 'mlp' = raw-lag MLP 168-64-64-1 ReLU + sigmoid; 'feat' = rolling-feature MLP (fixed linear layer = 10 block means of the
            window, see FEAT.BLOCKS, then 10-32-32-1 ReLU + sigmoid); 'feat24' = day-level feature MLP (6 block means, every block
            >= 24 h, FEAT.BLOCKS24, then 6-32-32-1 ReLU + sigmoid).  (Tried and discarded during set-up, before any ZEAL computation: a GAP
            fully-convolutional classifier (eval AUC 0.53, cannot localise recent hours) and a strided 1-D CNN (AUC 0.75, verifier
            behaviour indistinguishable from 'mlp' in a smoke test); recorded in findings.md.)
  split   : train weeks 1-20, early-stopping weeks 21-24, evaluation = the last 6 weeks (T = 1008 hourly outputs per
            feeder; each output uses the 167 preceding hours as context).
  perturbation (declared feature-uncertainty set): every hourly z-scored load value y_s of the evaluation series
            (T + W - 1 = 1175 values per feeder) may be off by at most eps (l_inf ball on the SERIES, shared by every
            sliding window that contains s).  eps in EPS_GRID (units: training-period standard deviations).
"""
